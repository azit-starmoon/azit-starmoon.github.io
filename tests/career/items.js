// 배치: 부마다 다섯 바퀴. 바퀴 안에서는 R, S, I, E, A, C처럼 맞은편이나 한 칸 건넌 유형이 이어지게 돌고
// (바로 앞뒤 문항이 같은 유형이나 이웃 유형이 아니다), 바퀴의 시작 칸을 0, 2, 4, 1, 3으로 옮겨
// 바퀴가 바뀌는 자리에서도 같은 유형이나 이웃 유형이 붙지 않는다.
const STEP = [0, 3, 1, 4, 2, 5];
const SHIFTS = [0, 2, 4, 1, 3];
function arrange(bank, part, offset) {
  const out = [];
  SHIFTS.forEach((sh, round) => {
    STEP.forEach((st) => {
      const t = TYPE_ORDER[(st + sh) % 6];
      const [text, r] = bank[t][round];
      out.push({ id: `${t}${offset + round + 1}`, text, type: t, r: !!r, part });
    });
  });
  return out;
}

