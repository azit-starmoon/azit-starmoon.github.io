// 육각형 위 거리: 0 같음, 1 이웃, 2 한 칸 건너, 3 맞은편
export function hexDist(a, b) {
  const d = Math.abs(TYPE_ORDER.indexOf(a) - TYPE_ORDER.indexOf(b));
  return Math.min(d, 6 - d);
}

