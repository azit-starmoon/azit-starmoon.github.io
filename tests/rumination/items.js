export const ITEMS = (() => {
  const out = [];
  for (let i = 0; i < 8; i++) {
    SCALE_ORDER.forEach((k) => {
      const [text, r] = BANK[k][i];
      out.push({ id: `${k}${i + 1}`, text, scale: k, r: !!r });
    });
  }
  return out;
})();
