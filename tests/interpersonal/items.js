// 원에서 이웃한 방향이 연달아 나오지 않도록 세 칸씩 건너뛰며 돌고(PA, FG, LM, BC, HI, NO, DE, JK), 회차마다 시작을 한 칸씩 민다
const STRIDE = [0, 3, 6, 1, 4, 7, 2, 5].map((k) => OCTANT_ORDER[k]);
export const ITEMS = (() => {
  const out = [];
  for (let i = 0; i < 5; i++) {
    for (let k = 0; k < 8; k++) {
      const o = STRIDE[(k + i) % 8];
      const [text, r] = BANK[o][i];
      out.push({ id: `${o}${i + 1}`, text, octant: o, r: !!r });
    }
  }
  return out;
})();
