// 덕목을 돌아가며 강점을 하나씩 뽑은 차례. 이웃한 문항이 같은 덕목에서 나오지 않는다.
export const MIX_ORDER = (() => {
  const queues = VIRTUE_ORDER.map((v) => [...VIRTUES[v].strengths]);
  const out = [];
  while (out.length < STRENGTH_ORDER.length) queues.forEach((q) => { if (q.length) out.push(q.shift()); });
  return out;
})();

// 강점마다 반대 방향 문항이 놓일 자리(0~3)를 MIX_ORDER 위치에 따라 돌려서,
// 어느 부에서나 반대 방향 문항이 네 문항에 하나꼴로 고르게 흩어지게 한다.
function slotsOf(s) {
  const j = MIX_ORDER.indexOf(s);
  const rSlot = (j + 2) % 4;
  const fw = [0, 1, 2];
  const slots = [];
  for (let k = 0; k < 4; k++) slots.push(k === rSlot ? { text: BANK[s][3], r: true, n: 4 } : { text: BANK[s][fw[0]], r: false, n: fw.shift() + 1 });
  return slots;
}

// 한 부 = 앞쪽 24문항(MIX_ORDER 차례) + 뒤쪽 24문항(MIX_ORDER를 반 바퀴 돌린 차례).
// 같은 강점의 두 문항은 최소 12문항 떨어진다.
function buildPart(p) {
  const rot = [...MIX_ORDER.slice(12), ...MIX_ORDER.slice(0, 12)];
  const pick = (s, k) => { const it = slotsOf(s)[k]; return { id: `${s}${it.n}`, text: it.text, strength: s, r: it.r }; };
  return [...MIX_ORDER.map((s) => pick(s, p * 2)), ...rot.map((s) => pick(s, p * 2 + 1))];
}

export const PART1_ITEMS = buildPart(0);
export const PART2_ITEMS = buildPart(1);
export const ALL_ITEMS = [...PART1_ITEMS, ...PART2_ITEMS];
