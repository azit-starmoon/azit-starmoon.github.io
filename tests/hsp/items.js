export const TRAIT_ITEMS = (() => {
  const out = [];
  for (let i = 0; i < 10; i++) {
    for (let k = 0; k < 4; k++) {
      const f = FACET_ORDER[(k + i) % 4];
      const [text, r] = BANK[f][i];
      out.push({ id: `${f}${i + 1}`, text, facet: f, r: !!r });
    }
  }
  return out;
})();

