// 배치: 네 바퀴. 바퀴마다 원형에서 세 칸씩 건너뛰며 고르므로, 바로 앞뒤 문항은 이웃한 가치가 아니다.
// 바퀴의 시작 칸을 0, 5, 9, 4로 두어 바퀴가 바뀌는 자리에서도 같은 가치나 이웃 가치가 붙지 않는다.
const STARTS = [0, 5, 9, 4];
export const ITEMS = (() => {
  const out = [];
  STARTS.forEach((st, round) => {
    for (let k = 0; k < VALUE_ORDER.length; k++) {
      const v = VALUE_ORDER[(st + 3 * k) % VALUE_ORDER.length];
      const [text, r] = BANK[v][round];
      out.push({ id: `${v}${round + 1}`, text, value: v, r: !!r });
    }
  });
  return out;
})();
