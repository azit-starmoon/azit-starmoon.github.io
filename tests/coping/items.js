// 같은 대처가 이어지지 않도록 여덟 가지를 돌아가며 섞는다(시작도 세 칸씩 민다)
export const COPE_ITEMS = (() => {
  const out = [];
  for (let i = 0; i < 5; i++) {
    for (let k = 0; k < 8; k++) {
      const key = STRATEGY_ORDER[(k + i * 3) % 8];
      const [text, r] = BANK[key][i];
      out.push({ id: `${key}${i + 1}`, text, strategy: key, r: !!r });
    }
  }
  return out;
})();

