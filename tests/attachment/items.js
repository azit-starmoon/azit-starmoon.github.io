// 같은 요인이 이어지지 않도록 불안과 회피를 번갈아 놓고, 거꾸로 채점하는 문항이 네 바퀴에 고루 퍼지도록 섞는다
const ROUND_ORDER = ['A1', 'V1', 'A2', 'V2', 'A3', 'V3', 'A4', 'V4'];
const OFFSET = { A1: 0, V1: 1, A2: 2, V2: 3, A3: 1, V3: 2, A4: 3, V4: 0 };

function buildGeneral() {
  const out = [];
  for (let r = 0; r < 4; r++) {
    ROUND_ORDER.forEach((f) => {
      const k = (r + OFFSET[f]) % 4;
      out.push({ id: `${f.toLowerCase()}_${k + 1}`, f, d: FACETS[f].d, key: k === 3 ? -1 : 1, text: FACET_ITEMS[f][k] });
    });
    out.push({ id: `m_${r + 1}`, f: 'M', d: 'amb', key: 1, text: AMB_ITEMS[r] });
  }
  return out;
}

export const GENERAL_ITEMS = buildGeneral();

