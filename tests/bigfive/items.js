// 출제 순서: 4라운드 × 하위 요인 6개 × 영역 N·E·O·A·C 순으로 돌아가며 섞는다
function buildOrder() {
  const order = [];
  for (let r = 0; r < 4; r++) {
    for (let f = 1; f <= 6; f++) {
      ['N', 'E', 'O', 'A', 'C'].forEach((d) => {
        const code = `${d}${f}`;
        const [text, key] = RAW[code][r];
        order.push({ id: `b${code}_${r + 1}`, facet: code, domain: d, key, text });
      });
    }
  }
  return order;
}

