// 고정 시드 셔플: 누구나 같은 순서로 풀고, 같은 유형 문항이 연달아 나오지 않게 한다
function mulberry32(seed) {
  return function () {
    seed |= 0; seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function buildOrder() {
  const rand = mulberry32(20261125);
  const shuffle = (arr) => {
    const a = arr.slice();
    for (let i = a.length - 1; i > 0; i--) {
      const j = Math.floor(rand() * (i + 1));
      [a[i], a[j]] = [a[j], a[i]];
    }
    return a;
  };
  const order = [];
  let prev = 0;
  for (let round = 0; round < 10; round++) {
    let perm = shuffle([1, 2, 3, 4, 5, 6, 7, 8, 9]);
    while (perm[0] === prev) perm = shuffle(perm);
    perm.forEach((t) => order.push({ t, i: round }));
    prev = perm[perm.length - 1];
  }
  return order;
}

