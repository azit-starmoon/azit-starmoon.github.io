export const ITEMS = (() => {
  const out = [];
  for (let i = 0; i < 5; i++) {
    for (let k = 0; k < SEQ.length; k++) {
      const key = SEQ[(k + i * 4) % SEQ.length];
      const [text, r] = BANK[key][i];
      out.push({ id: `${key}${i + 1}`, text, factor: key, r: !!r });
    }
  }
  return out;
})();
