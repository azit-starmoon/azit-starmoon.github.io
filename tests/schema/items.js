// 같은 도식이 이어지지 않도록 다섯 바퀴에 걸쳐 섞는다. 바퀴마다 도식 순서를 다르게 돌린다.
function buildItems() {
  const out = [];
  const n = SCHEMA_ORDER.length;
  for (let r = 0; r < 5; r++) {
    const shift = (r * 7) % n;
    for (let i = 0; i < n; i++) {
      const s = SCHEMA_ORDER[(i * 5 + shift) % n];
      out.push({ id: `${s}_${r + 1}`, s, text: TEXT[s][r] });
    }
  }
  return out;
}

export const ITEMS = buildItems();

